#!/usr/bin/env python3
"""What the weather draws the townsfolk to (docs/indoor_weather.md, backlog item 28): writes
Content/PeopleData/weather_pull.json, read by PeopleSim (FWorld::LoadWeatherPull).

Each row names place kinds or place ids and how strongly each weather pulls people there, on the scale of a choice's
score (1 is a strong wish; the rain's penalty out of doors is about 1-1.7). PeopleSim adds the pull to the score of a free
activity at such a place and, choosing between places, takes PullMeters (160 m) of walking off per unit. A place takes the
first row naming its id, else the first naming its kind.

  rain  scales from 0.6 (a drizzle) to 1 (4 mm/h and more)
  cold  below 2 C, full at -6 C
  hot   above 22 C in the dry sun, full at 28 C
  storm wind above 12 m/s, full at 20 m/s
  dark  after sunset

  python3 tools/town/weather_pull.py           write it
  python3 tools/town/weather_pull.py --check   only check that the written file is current and every kind and id exists
"""
import json
import os
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
DATA = os.path.join(ROOT, "unreal", "Lyudmilovsk", "Content", "PeopleData")
OUT = os.path.join(DATA, "weather_pull.json")

PULL = [
    # the ice-cream freezer kiosk by the promenade (talk.json tone_by: cold_counter): a queue on a hot afternoon
    dict(places=["P-KIOSK2"], hot=2.0, about="the ice-cream kiosk"),
    # the cafes and the restaurant fill in the rain and the cold, a little in the evening; a cold drink on a hot day
    dict(kinds=["cafe", "restaurant"], rain=0.9, cold=0.5, storm=0.5, hot=0.25, dark=0.1, about="cafes and the restaurant"),
    dict(kinds=["library"], rain=0.8, cold=0.4, storm=0.4, about="the library's reading room"),
    # the club hall up on the spur and the town's two culture clubs and the hall: company under a roof, evenings too
    dict(kinds=["club", "culture_club", "hall"], rain=0.7, cold=0.4, storm=0.5, dark=0.2, about="the clubs and the hall"),
    dict(kinds=["culture"], rain=0.6, cold=0.3, about="the sport hall"),
    # the sanatorium (its visit spots) and its lounge's dominoes (item 26): the pensioners' rainy afternoon
    dict(kinds=["hotel", "sanatorium_lounge"], rain=0.6, cold=0.4, storm=0.4, about="the sanatorium and its lounge"),
    # the cinema's day and evening shows (item 26): a film is what a wet evening is for
    dict(kinds=["cinema_hall"], rain=0.8, cold=0.4, storm=0.5, dark=0.15, about="the cinema hall"),
    # shops under a roof: errands are run in the rain anyway, a little more willingly there
    dict(kinds=["shop", "market"], rain=0.25, cold=0.2, about="shops and the market hall"),
]

KEYS = ("rain", "cold", "hot", "storm", "dark")

# activities of this file, added after activities.json's (PeopleSim LoadActivities append): "shelter": chosen only at a
# place the weather pulls to now (0.3 and more), so on a fine day nobody thinks of it
ACTIVITIES = [
    {"id": "shelter", "places": ["cafe", "restaurant", "library", "culture_club", "hall", "culture", "hotel", "shop", "market"],
     "slots": ["visit"], "pose": "stand", "minutes": [30, 90], "hours": [8, 21.5],
     "meets": {"social": 0.45, "fun": 0.3, "mind": 0.1}, "base": 0.0, "trait": "social", "shelter": 1,
     "about": "waiting out the rain or the frost under a roof: a cup at the counter, the papers in the library, the club's hall"},
]


def build():
    rows = []
    for r in PULL:
        row = {}
        if r.get("kinds"):
            row["kinds"] = r["kinds"]
        if r.get("places"):
            row["places"] = r["places"]
        for k in KEYS:
            if r.get(k):
                row[k] = r[k]
        row["about"] = r["about"]
        rows.append(row)
    return {"_doc": "What the weather draws the townsfolk to (generated by tools/town/weather_pull.py; docs/indoor_weather.md).",
            "pull": rows, "activities": ACTIVITIES}


def problems():
    kinds, ids = set(), set()
    for name in ("town_places.json", "people_places.json"):
        path = os.path.join(DATA, name)
        if not os.path.exists(path):
            continue
        d = json.load(open(path, encoding="utf-8"))
        for p in d.get("places", []):
            kinds.add(p.get("kind", ""))
            ids.add(p.get("id", ""))
        if "club" in d:
            kinds.add("club")     # people_places.json's "club": the club hall (PeopleSim makes it a place of kind club)
    out = []
    acts = json.load(open(os.path.join(DATA, "activities.json"), encoding="utf-8"))["activities"]
    have = {a["id"] for a in acts}
    for a in ACTIVITIES:
        if a["id"] in have:
            out.append("activity %r is in activities.json already" % a["id"])
        for k in a["places"]:
            if k not in kinds:
                out.append("activity %s: no place of kind %r" % (a["id"], k))
    for r in PULL:
        for k in r.get("kinds", []):
            if k not in kinds:
                out.append("no place of kind %r" % k)
        for i in r.get("places", []):
            if i not in ids:
                out.append("no place %r" % i)
        for k in KEYS:
            if not 0.0 <= r.get(k, 0.0) <= 2.0:
                out.append("%s: %s out of 0..2" % (r["about"], k))
    return out


def main():
    text = json.dumps(build(), ensure_ascii=False, indent=1) + "\n"
    probs = problems()
    for p in probs:
        print("PROBLEM", p)
    if "--check" in sys.argv[1:]:
        cur = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        stale = cur != text
        print("weather_pull: %d rows; %d problems%s" % (len(PULL), len(probs), ", STALE (run without --check)" if stale else ", 0 stale"))
        return 1 if probs or stale else 0
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print("weather_pull: %d rows; %d problems -> %s" % (len(PULL), len(probs), os.path.relpath(OUT, ROOT)))
    return 1 if probs else 0


if __name__ == "__main__":
    sys.exit(main())
