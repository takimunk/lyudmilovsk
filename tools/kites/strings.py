def build(lang_i, path):
    with open(path, encoding="utf-8") as f:
        d = json.load(f, object_pairs_hook=collections.OrderedDict)
    # refreshed where they stand, new ones added at the end: tools/kites/town.py keeps its own keys in the same tables
    for k, v in WORDS.items():
        d[k] = v[lang_i]
    return json.dumps(d, ensure_ascii=False, indent=1) + "\n"


def main():
    stale = []
    for i, lang in enumerate(("ru", "en", "ja")):
        path = TABLE % lang
        text = build(i, path)
        if open(path, encoding="utf-8").read() != text:
            stale.append(path)
            if "--check" not in sys.argv:
                with open(path, "w", encoding="utf-8") as f:
                    f.write(text)
                print("wrote", os.path.relpath(path, ROOT))
    if "--check" in sys.argv:
        for p in stale:
            print("kites/strings: %s is not up to date (python3 tools/kites/strings.py)" % os.path.relpath(p, ROOT))
        sys.exit(1 if stale else 0)
    print("kite words: %d keys in ru/en/ja" % len(WORDS))


if __name__ == "__main__":
    main()
