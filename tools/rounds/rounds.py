"""The bicycle rounds (docs/rounds.md): the morning paper round and the post round, made from the town plan's addresses.

  python3 tools/rounds/rounds.py           writes unreal/Lyudmilovsk/Content/City/rounds.json
  python3 tools/rounds/rounds.py --check   fails if the file is not what this script makes now (run after a plan change)

Sources: Content/City/city_plan.json (the wall flats' doors on terraces T1-T4, kiosk 1) and Content/PeopleData/townsfolk.json
(who lives behind which door). Everything is picked by rule, never by a resident's key written here, so a plan change that
renames the townsfolk only needs this script run again.

- paper: one route per terrace (T1..T4), the subscribers' doors along the stretch of the terrace nearest the kiosk, in the
  order a rider meets them coming from the kiosk end; the round of the day is the day's terrace (days since the start, mod 4).
- post: the flats with somebody living there (not "away") on the same stretches; the engine picks the day's parcels.
- postman: the oldest pensioner living in a flat of the lower town (T1): forty years with the bag, the knees gone now, he gives
  the hero the day's parcels at his own door.
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CONTENT = os.path.join(ROOT, "unreal", "Lyudmilovsk", "Content")
OUT = os.path.join(CONTENT, "City", "rounds.json")

TERRACES = ["T1", "T2", "T3", "T4"]
# the stretch of every terrace the rounds keep to (Unreal Y, cm): from the kiosk's end to the cascade round the Academgorodok
STRETCH = (40500.0, 78000.0)
PAPERS_PER_ROUTE = 12
SPARE_PAPERS = 4
PARCELS_PER_DAY = 5


def load(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def spread(items, n):
    """n items spread evenly over a list (its order kept)."""
    if len(items) <= n:
        return list(items)
    step = len(items) / float(n)
    return [items[int(i * step + step / 2)] for i in range(n)]


def build():
    plan = load(os.path.join(CONTENT, "City", "city_plan.json"))
    folk = load(os.path.join(CONTENT, "PeopleData", "townsfolk.json"))["people"]
    flats = {d["id"]: d for d in plan["wall_dwellings"]}
    kiosk = next(p for p in plan["plots"] if p["id"] == "P-KIOSK1")

    def stop(d, person=""):
        x, y, z = d["door_ue"]
        return {"id": d["id"], "terrace": d["terrace"], "at": [round(x, 1), round(y, 1), round(z, 1)], "yaw": d["yaw"],
                "person": person}

    def on_stretch(d):
        return STRETCH[0] <= d["door_ue"][1] <= STRETCH[1]

    routes = []
    for t in TERRACES:
        doors = sorted([d for d in plan["wall_dwellings"] if d["terrace"] == t and on_stretch(d)], key=lambda d: d["door_ue"][1])
        routes.append({"id": "paper_" + t.lower(), "terrace": t, "stops": [stop(d) for d in spread(doors, PAPERS_PER_ROUTE)]})

    living = {}
    for p in folk:
        home = p.get("home", "")
        if home in flats and p.get("occupation") != "away" and p.get("age", 0) >= 16:
            living.setdefault(home, []).append(p)
    post = []
    for fid in sorted(living, key=lambda f: (flats[f]["terrace"], flats[f]["door_ue"][1])):
        d = flats[fid]
        if d["terrace"] in TERRACES and on_stretch(d):
            # the parcel is for the eldest of the flat (the one who ordered from the catalogue)
            who = sorted(living[fid], key=lambda p: (-p.get("age", 0), p["key"]))[0]
            post.append(stop(d, who["key"]))

    pens = [p for p in folk if p.get("occupation") == "pensioner" and p.get("home", "") in flats
            and flats[p["home"]]["terrace"] == "T1" and not p.get("female")]
    postman = sorted(pens, key=lambda p: (-p.get("age", 0), p["key"]))[0]

    fx, fy, fz = kiosk["ue"]
    front = kiosk.get("front")
    # the bundle lies on the kiosk's step: the plan's front point, in the plot's Unreal frame (ue - map*100 is the plot's offset)
    ox, oy = fx - kiosk["map"][0] * 100.0, fy - kiosk["map"][1] * 100.0
    bundle = [round(front[0] * 100.0 + ox, 1), round(front[1] * 100.0 + oy, 1), round(fz, 1)]

    return {
        "_doc": "Generated by tools/rounds/rounds.py (docs/rounds.md) from Content/City/city_plan.json and "
                "Content/PeopleData/townsfolk.json. Do not edit.",
        "paper": {"bundle": bundle, "from": 6.0, "until": 7.5, "deadline": 8.0, "spare": SPARE_PAPERS, "routes": routes},
        "post": {"postman": postman["key"], "door": stop(flats[postman["home"]], postman["key"]), "from": 9.0, "until": 12.0,
                 "deadline": 14.0, "days": [2, 3, 4, 5, 6], "parcels": PARCELS_PER_DAY, "stops": post},
    }


def check(d):
    probs = []
    for r in d["paper"]["routes"]:
        n = len(r["stops"])
        if n < 8:
            probs.append("%s: only %d doors" % (r["id"], n))
        length = sum(((a["at"][0] - b["at"][0]) ** 2 + (a["at"][1] - b["at"][1]) ** 2) ** 0.5 for a, b in zip(r["stops"], r["stops"][1:])) / 100.0
        if not 150.0 <= length <= 900.0:
            probs.append("%s: %.0f m along the doors (a round is 150-900 m)" % (r["id"], length))
        ids = [s["id"] for s in r["stops"]]
        if len(set(ids)) != len(ids):
            probs.append("%s: a door twice" % r["id"])
    if len(d["post"]["stops"]) < 4 * d["post"]["parcels"]:
        probs.append("post: only %d flats with somebody in them" % len(d["post"]["stops"]))
    return probs


def main():
    d = build()
    probs = check(d)
    for p in probs:
        print("ERROR:", p)
    text = json.dumps(d, ensure_ascii=False, indent=1) + "\n"
    if "--check" in sys.argv:
        old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if old != text:
            print("ERROR: %s is not what tools/rounds/rounds.py makes now: run it" % os.path.relpath(OUT, ROOT))
            sys.exit(1)
    else:
        with open(OUT, "w", encoding="utf-8") as f:
            f.write(text)
        print("wrote", os.path.relpath(OUT, ROOT))
    for r in d["paper"]["routes"]:
        print("paper %s: %d doors" % (r["id"], len(r["stops"])))
    print("post: %d flats, postman %s at %s" % (len(d["post"]["stops"]), d["post"]["postman"], d["post"]["door"]["id"]))
    sys.exit(1 if probs else 0)


if __name__ == "__main__":
    main()
