ORDER = {"first": 0, "again": 1, "sun": 2, "quest": 3, "aside": 4}


def stage_ids(q):
    out = {"done"}
    for st in q["stages"]:
        out.add(st["id"])
        if any(o["event"] == "bring" for o in st["objectives"]):
            out.add(st["id"] + "_empty")
    return out


def split_kind(kind):
    """quest.<q>.<stages>[.if.<cond>][.again] -> (head, quest, [stages], tail)"""
    head, _, rest = kind.partition(".")
    quest, _, rest = rest.partition(".")
    tail = ""
    m = re.search(r"(\.if\..*|\.again)$", rest)
    if m:
        tail = rest[m.start():]
        rest = rest[:m.start()]
    stages = rest.split(",")
    if quest == "ship_voyage":      # the people's days: Saturday and Sunday are two stages each
        stages = [x for st in stages for x in DAYS.get(st, [st])]
    return head, quest, stages, tail


def dialogue_block(people, quests, strings):
    qs = {q["id"]: q for q in quests}
    all_ids = {q["id"] for q in QUESTS}
    out = [DLG_BEGIN]
    remarks = []
    used = set()
    for pid in PEOPLE:
        exs = people.get(pid, [])
        rows = []
        for ex in exs:
            head = ex.kind.split(".")[0]
            kind = ex.kind
            if not ex.keys:
                err("%s: %s %s has no lines" % (ex.where, pid, ex.kind))
                continue
            if head in ("quest", "aside", "remark"):
                h, quest, stages, tail = split_kind(kind)
                if quest not in all_ids:
                    err("%s: no quest %s" % (ex.where, quest))
                    continue
                if quest not in qs:
                    continue      # the quest waits (see final_quests): its words wait with it
                known = stage_ids(qs[quest])
                orig = stage_ids(next(q for q in QUESTS if q["id"] == quest))
                for s in stages:
                    if s not in orig:
                        err("%s: quest %s has no stage %s" % (ex.where, quest, s))
                stages = [s for s in stages if s in known]
                if not stages:
                    continue
                for c in re.findall(r"(?:done|on):(\w+)", tail):
                    if c not in qs:
                        stages = []
                if not stages:
                    continue
                if head == "remark":
                    r = {"id": "%s_%s" % (pid, ex.scene), "person": pid, "quest": quest, "stages": stages, "within_m": 6,
                         "lines": list(ex.keys)}
                    dk = "journal.heard.%s_%s" % (pid, ex.scene)
                    if dk in strings:
                        r["diary"] = dk
                    remarks.append(r)
                    used.update(ex.keys)
                    continue
                kind = "%s.%s.%s%s" % (h, quest, ",".join(stages), tail)
            elif head not in ("first", "again", "sun"):
                err("%s: kind %s?" % (ex.where, ex.kind))
                continue
            done = head == "quest" and ".done" in "." + kind.split(".", 2)[2]
            rows.append((ORDER[head] + (2 if done and head == "quest" else 0), len(rows), kind, ex.keys))
            used.update(ex.keys)
        if not rows:
            continue
        if not any(r[2] == "first" for r in rows):
            err("%s has no first talk" % pid)
        out.append("")
        out.append("[%s]" % body(pid))
        for _, _, kind, keys in sorted(rows, key=lambda r: (r[0], r[1])):
            out.append("%s = %s" % (kind, " | ".join(keys)))
    out.append(DLG_END)
    return "\n".join(out) + "\n", remarks, used


def merge_dialogue(text, block):
    if DLG_BEGIN in text:
        a = text.index(DLG_BEGIN)
        b = text.index(DLG_END) + len(DLG_END)
        rest = text[:a].rstrip("\n") + "\n" + text[b:].lstrip("\n")
    else:
        rest = text
    return rest.rstrip("\n") + "\n\n" + block


