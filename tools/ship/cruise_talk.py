def game_facts():
    code = []
    for p in glob.glob(os.path.join(SOURCE, "**", "*.cpp"), recursive=True) + glob.glob(os.path.join(SOURCE, "**", "*.h"), recursive=True):
        with open(p, encoding="utf-8", errors="replace") as f:
            code.append((os.path.basename(p), f.read()))
    text = "\n".join(t for _, t in code)
    f = {}
    f["events"] = set(re.findall(r'Notify\([^;\n]*?TEXT\("([a-z_]+)"\)', text))
    f["commands"] = {c.lower() for c in re.findall(r'(?:FAutoConsoleCommand\w*|TAutoConsoleVariable<[^>]*>|FAutoConsoleVariableRef)\s+\w+\(\s*TEXT\("([^"]+)"\)', text)}
    inv = next((t for n, t in code if n == "LyudInventory.cpp"), "")
    f["items"] = set(re.findall(r'TEXT\("(\w+)"\)', inv))
    inter_path = os.path.join(CONTENT, "City", "interiors.json")
    acts = {}
    if os.path.exists(inter_path):
        inter = load(inter_path)
        used = {t.get("act") for t in inter.get("things", [])}
        for aid, a in inter.get("acts", {}).items():
            if aid in used and a.get("event"):
                acts.setdefault(a["event"], set()).add(a.get("target", ""))
                if a.get("game"):      # an act with a game also sends win / lose / draw <target>
                    acts.setdefault("win", set()).add(a.get("target", ""))
        f["texts"] = set(inter.get("texts", {}) or {})
        f["stamps"] = {"%s/%s" % (cid, p if isinstance(p, str) else p.get("id", "")) for cid, c in (inter.get("collections", {}) or {}).items()
                       for p in (c.get("pieces", []) if isinstance(c, dict) else [])}
    else:
        f["texts"], f["stamps"] = set(), set()
    f["acts"] = acts
    tps = set()
    for p in glob.glob(os.path.join(CONTENT, "Dev", "teleports", "*.json")):
        try:
            tps |= {t["id"] for t in load(p).get("teleports", []) if "id" in t}
        except ValueError:
            pass
    f["teleports"] = tps | set(re.findall(r'FAutoTeleport\s+\w+\(TEXT\("(\w+)"\)', text))
    ship_people = os.path.join(CONTENT, "PeopleData", "ship_people.json")
    f["ship_people"] = {p.get("key") for p in load(ship_people).get("people", [])} if os.path.exists(ship_people) else set()
    # may a dev block walk the hero to a ship person? only when the quest tests know the ship's people file
    qsim = read(os.path.join(ROOT, "tools", "questsim", "questsim.py"))
    f["goto_ok"] = "ship_people" in qsim
    return f


def event_ok(f, ev, target):
    """None if the game can send it; else why not."""
    if ev in ("talk", "bring", "have"):
        return None
    if ev in ("do", "win"):
        if target in f["acts"].get(ev, ()):
            return None
        return "no act of Content/City/interiors.json sends %s %s" % (ev, target)
    if ev not in f["events"]:
        return "the game's code sends no %s event yet" % ev
    return None


def final_quests(f):
    """The quests as they can be played today: a stage whose objective cannot happen yet is left out when the quest has
    'optional' set for it, else the quest waits out of the data."""
    optional = set()
    out, waiting = [], {}
    for q in QUESTS:
        stages, why = [], None
        for st in q["stages"]:
            bad = [event_ok(f, o["event"], o["target"]) for o in st["objectives"]]
            bad = [b for b in bad if b]
            if bad:
                if (q["id"], st["id"]) in optional:
                    notes.append("%s: stage %s left out for now (%s)" % (q["id"], st["id"], bad[0]))
                    continue
                why = "%s.%s: %s" % (q["id"], st["id"], bad[0])
                break
            stages.append(st)
        if not why and q.get("start_on") and event_ok(f, q["start_on"]["event"], q["start_on"]["target"]):
            why = "%s: start: %s" % (q["id"], event_ok(f, q["start_on"]["event"], q["start_on"]["target"]))
        if why:
            waiting[q["id"]] = why
            continue
        out.append(dict(q, stages=stages))
    # a quest that hangs on another (the two ends of the card sharp) waits with it; rewards start only what is there
    changed = True
    while changed:
        changed = False
        ids = {q["id"] for q in out}
        for q in list(out):
            if q.get("needs") and q["needs"] not in ids:
                out.remove(q)
                waiting[q["id"]] = "%s waits with %s" % (q["id"], q["needs"])
                changed = True
    ids = {q["id"] for q in out}
    started = {s for q in out for st in q["stages"] for s in (st.get("reward") or {}).get("start", []) if s in ids}
    for q in list(out):
        if not q.get("start_on") and q["id"] not in started:
            out.remove(q)
            waiting[q["id"]] = "%s: nothing begins it" % q["id"]
    for w in waiting.values():
        notes.append("WAITS " + w)
    return out, waiting


def quest_json(q, f, ids):
    body_ = {"id": q["id"], "kind": "side"}
    if q.get("start_on"):
        body_["start_on"] = q["start_on"]
    stages = []
    for st in q["stages"]:
        s = {"id": st["id"], "objectives": st["objectives"]}
        if st.get("no_skip"):
            s["no_skip"] = True
        rw = st.get("reward")
        if rw:
            r = {}
            if rw.get("rubles"):
                r["rubles"] = rw["rubles"]
            items = {}
            for it, n in (rw.get("items") or {}).items():
                if it in f["items"]:
                    items[it] = n
                else:
                    notes.append("%s.%s: reward item %s is not in LyudInventory.cpp yet: left out" % (q["id"], st["id"], it))
            if items:
                r["items"] = items
            start = [s2 for s2 in rw.get("start", []) if s2 in ids]
            if start:
                r["start"] = start
            if r:
                s["reward"] = r
        d = st.get("dev")
        if d:
            block, ex = {}, []
            tp = d["tp"] or NEAR.get(d["who"])
            if tp and tp in f["teleports"]:
                block["tp"] = tp
            give = {it: n for it, n in d["give"].items() if it in f["items"]}
            if give:
                block["give"] = give
            if "lyud.cruise.board" in f["commands"]:
                ex.append("lyud.Cruise.Board")
            if d["jump"] and "lyud.cruise.jump" in f["commands"]:
                ex.append("lyud.Cruise.Jump %s" % d["jump"])
            for m in d["more"]:
                if m.split()[0].lower() in f["commands"]:
                    ex.append(m)
            if d["who"] and f["goto_ok"] and d["who"] in f["ship_people"] and "quest.gotoperson" in f["commands"]:
                ex.append("Quest.GoToPerson %s" % d["who"])
            if ex:
                block["exec"] = ex
            if block:
                s["dev"] = block
        stages.append(s)
    body_["stages"] = stages
    text = json.dumps(body_, ensure_ascii=False, separators=(", ", ": "))
    return "  " + text[:-1] + ", " + MARK + "}"


def merge_quests(text, mine):
    lines = [l for l in text.split("\n") if MARK not in l]
    end = max(i for i, l in enumerate(lines) if l.strip() == "]")
    first_city = next((i for i, l in enumerate(lines) if CITY_MARK in l), None)
    at = first_city if first_city is not None else end
    prev = at - 1
    while not lines[prev].strip():
        prev -= 1
    lines[prev] = lines[prev].rstrip()
    if lines[prev].endswith(","):
        lines[prev] = lines[prev][:-1]
    more_after = first_city is not None
    if mine or more_after:
        lines[prev] += ","
    ours = [m + ("," if (i < len(mine) - 1 or more_after) else "") for i, m in enumerate(mine)]
    return "\n".join(lines[:prev + 1] + ours + lines[prev + 1:])


