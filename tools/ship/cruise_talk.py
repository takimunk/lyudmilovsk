def main():
    check = "--check" in sys.argv
    stats = "--stats" in sys.argv
    strings, people = parse_talk()
    f = game_facts()
    quests, waiting = final_quests(f)
    ids = {q["id"] for q in quests}
    out = {}

    # the quests
    qpath = os.path.join(CONTENT, "UI", "quests.json")
    out[qpath] = merge_quests(read(qpath), [quest_json(q, f, ids) for q in quests])

    # the dialogue and the remarks
    block, remarks, used = dialogue_block(people, quests, strings)
    dpath = os.path.join(CONTENT, "Dialogue", "npc_dialogue.txt")
    out[dpath] = merge_dialogue(read(dpath), block)
    spath = os.path.join(CONTENT, "UI", "quest_scenes.json")
    stext = read(spath)
    scenes = json.loads(stext)
    scenes["remarks"] = [r for r in scenes.get("remarks", []) if not str(r.get("id", "")).startswith("ship_")] + remarks
    out[spath] = json.dumps(scenes, ensure_ascii=False, indent=1) + ("\n" if stext.endswith("\n") else "")

    # the words: every line that is said, the quests' own, the diary's
    table = {}
    for q in quests:
        need = ["quest.%s.title" % q["id"], "quest.%s.desc" % q["id"], "quest.%s.done" % q["id"]]
        for st in q["stages"]:
            need.append("quest.%s.%s.log" % (q["id"], st["id"]))
            need += ["quest.%s.%s.obj" % (q["id"], o["id"]) for o in st["objectives"]]
        for k in need:
            if k not in strings:
                err("no words for %s" % k)
            else:
                table[k] = strings[k]
    for k in sorted(used):
        full = "line." + k
        if full not in strings:
            err("line %s is used but not written" % full)
        else:
            table[full] = strings[full]
    for r in remarks:
        if r.get("diary"):
            table[r["diary"]] = strings[r["diary"]]
    for k, v in strings.items():
        for l in LANGS:
            if not v.get(l):
                err("%s: no %s" % (k, l))
        if k.startswith("line.") and len(v.get("ja", "")) > 110:
            err("%s: the Japanese line is %d characters (110 at most)" % (k, len(v["ja"])))
        if k.startswith("line.") and (len(v.get("ru", "")) > 230 or len(v.get("en", "")) > 250):
            err("%s: too long for a spoken line (ru %d, en %d)" % (k, len(v.get("ru", "")), len(v.get("en", ""))))
    unused = [k for k in strings if k not in table and not any(k.startswith("quest.%s." % w) for w in waiting)
              and not k.startswith("journal.heard.")]
    waiting_lines = [k for k in unused if k.startswith("line.")]
    for l in LANGS:
        path = os.path.join(CONTENT, "Localization", TABLE, "strings_%s.json" % l)
        out[path] = json.dumps({k: v[l] for k, v in table.items()}, ensure_ascii=False, indent=1) + "\n"

    # the voices
    vpath = os.path.join(ROOT, "localization", "voice.json")
    vtext = read(vpath)
    voice = json.loads(vtext)
    speakers = {k: v for k, v in voice["speakers"].items() if not k.startswith("ship_")}
    pool = {v.get("voice"): v.get("voice_id") for v in voice["speakers"].values() if isinstance(v, dict) and v.get("voice") and v.get("voice_id")}
    for pid in PEOPLE:
        if not any(k.startswith("line.%s." % pid) for k in table):
            continue
        name, direction = VOICES[pid]
        entry = {"skip": "the motor ship's people (docs/ship.md): written, not voiced yet; proposed voice below",
                 "voice": name, "direction": direction}
        if name in pool:
            entry["voice_id"] = pool[name]
        elif name in voice["speakers"]:
            entry["like"] = name
        speakers[pid] = entry
    voice["speakers"] = speakers
    new_v = json.dumps(voice, ensure_ascii=False, indent=1) + ("\n" if vtext.endswith("\n") else "")
    out[vpath] = new_v

    stale = [p for p, t in out.items() if not os.path.exists(p) or read(p) != t]
    for n in notes:
        print("note: " + n)
    if waiting_lines:
        print("note: %d lines wait with their quests or stages (written, not in the table)" % len(waiting_lines))
    if stats:
        per = {}
        for k in table:
            if k.startswith("line."):
                per[k.split(".")[1]] = per.get(k.split(".")[1], 0) + 1
        print("quests: %d (%s)" % (len(quests), ", ".join(q["id"] for q in quests)))
        print("line keys: %d (x3 languages), other strings: %d" % (sum(per.values()), len(table) - sum(per.values())))
        for l in LANGS:
            print("  %s: %d characters spoken" % (l, sum(len(v[l]) for k, v in table.items() if k.startswith("line."))))
        print("per speaker: " + ", ".join("%s %d" % kv for kv in sorted(per.items())))
        print("remarks: %d" % len(remarks))
    if problems:
        for p in problems:
            print("PROBLEM " + p)
        print("%d problems: nothing written" % len(problems))
        return 1
    if check:
        for p in stale:
            print("stale: " + os.path.relpath(p, ROOT))
        print("check ok" if not stale else "%d stale" % len(stale))
        return 1 if stale else 0
    for p in stale:
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, "w", encoding="utf-8") as fh:
            fh.write(out[p])
        print("wrote " + os.path.relpath(p, ROOT))
    if not stale:
        print("nothing to write")
    return 0


if __name__ == "__main__":
    sys.exit(main())
