class Exchange:
    def __init__(self, pid, kind, scene, where):
        self.pid, self.kind, self.scene, self.where = pid, kind, scene, where
        self.keys = []   # without 'line.'


def parse_talk():
    strings = {}     # key -> {lang: text}
    people = {}      # pid -> [Exchange]
    for path in sorted(glob.glob(os.path.join(TALK, "*.txt"))):
        name = os.path.basename(path)
        lines = [l.rstrip("\n") for l in read(path).split("\n")]
        i, pid, ex = 0, None, None

        def three(i, where):
            got = []
            while len(got) < 3:
                i += 1
                if i >= len(lines) or not lines[i].strip() or lines[i][0] in "@[>-=#":
                    err("%s: %s: needs three lines (ru, en, ja)" % (where, key))
                    return i - 1, None
                got.append(lines[i].strip())
            return i, dict(zip(LANGS, got))

        while i < len(lines):
            l = lines[i]
            where = "%s:%d" % (name, i + 1)
            if not l.strip() or l.startswith("#"):
                pass
            elif l.startswith("@"):
                key = l[1:].strip()
                i, val = three(i, where)
                if val:
                    if key in strings:
                        err("%s: %s written twice" % (where, key))
                    strings[key] = val
            elif l.startswith("["):
                pid = l.strip()[1:-1]
                if pid not in PEOPLE:
                    err("%s: nobody %s" % (where, pid))
                people.setdefault(pid, [])
                ex = None
            elif l.startswith(">"):
                m = re.match(r">\s*(\S+)\s*:\s*(\w+)\s*$", l)
                if not m or pid is None:
                    err("%s: an exchange is '> kind : scene' inside a person's block" % where)
                else:
                    ex = Exchange(pid, m.group(1), m.group(2), where)
                    people[pid].append(ex)
            elif l.startswith("="):
                if ex is None:
                    err("%s: '=' outside an exchange" % where)
                else:
                    ex.keys += [k.strip() for k in l[1:].split("|") if k.strip()]
            elif l.startswith("-"):
                who = l[1:].strip()
                if ex is None:
                    err("%s: a line outside an exchange" % where)
                    i += 3
                else:
                    n = len(ex.keys) + 1
                    if who == "hero":
                        short = "hero.%s_%s.%d" % (ex.pid, ex.scene, n)
                    else:
                        sp = ex.pid if who == "me" else who
                        if sp not in PEOPLE:
                            err("%s: speaker %s?" % (where, who))
                        short = "%s.%s.%d" % (sp, ex.scene, n)
                    key = "line." + short
                    i, val = three(i, where)
                    if val:
                        if key in strings:
                            err("%s: %s written twice (scene names are one per person)" % (where, key))
                        strings[key] = val
                        ex.keys.append(short)
            else:
                err("%s: stray text: %s" % (where, l[:50]))
            i += 1
    return strings, people


